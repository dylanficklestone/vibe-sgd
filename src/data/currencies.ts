/**
 * Generate historical rate points for a given currency code against SGD
 */
export function generateHistoricalRates(
  currency: Currency,
  range: TimeRange
): HistoricalRatePoint[] {
  const pointsCount = range === '1D' ? 24 : range === '1W' ? 7 : range === '1M' ? 30 : range === '3M' ? 45 : 60;
  const baseRate = currency.rateAgainstSgd;
  const now = new Date();
  const results: HistoricalRatePoint[] = [];

  // Seeded deterministic variation based on code
  const seed = currency.code.charCodeAt(0) + currency.code.charCodeAt(currency.code.length - 1);
  const maxVariance = range === '1D' ? 0.003 : range === '1W' ? 0.008 : range === '1M' ? 0.02 : 0.05;

  for (let i = pointsCount - 1; i >= 0; i--) {
    const d = new Date(now);
    if (range === '1D') {
      d.setHours(d.getHours() - i);
    } else if (range === '1W') {
      d.setDate(d.getDate() - i);
    } else if (range === '1M') {
      d.setDate(d.getDate() - i);
    } else if (range === '3M') {
      d.setDate(d.getDate() - (i * 2));
    } else {
      d.setDate(d.getDate() - (i * 6));
    }

    const t = (pointsCount - i) / pointsCount;
    // Controlled wave variation with gentle random walk
    const wave = Math.sin((t * Math.PI * 3) + seed) * (maxVariance * 0.6);
    const noise = (Math.sin(i * 13.7 + seed) * 0.4) * (maxVariance * 0.4);
    const trend = (t - 0.5) * (currency.change24h * 0.01);
    const adjustedRate = baseRate * (1 + wave + noise + trend);

    const dateStr = range === '1D'
      ? d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : d.toLocaleDateString([], { month: 'short', day: 'numeric' });

    results.push({
      date: dateStr,
      rate: Number(adjustedRate.toFixed(currency.decimals > 2 ? 4 : 2)),
    });
  }

  // Ensure last point matches current live rate
  if (results.length > 0) {
    results[results.length - 1].rate = baseRate;
  }

  return results;
}
